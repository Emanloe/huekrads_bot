def _plural_rounds(value):
    value = int(value)
    if value % 10 == 1 and value % 100 != 11:
        return "раунд"
    if 2 <= value % 10 <= 4 and not 12 <= value % 100 <= 14:
        return "раунда"
    return "раундов"


def _legacy_plural_rounds_early(n: int) -> str:
    if n % 10 == 1 and n % 100 != 11:
        return "раунд"
    if 2 <= n % 10 <= 4 and (n % 100 < 10 or n % 100 >= 20):
        return "раунда"
    return "раундов"


